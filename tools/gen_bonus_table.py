#!/usr/bin/env python3
"""Generate the table of simple improvement handlers from Chummer's source.

Chummer turns each `<bonus>` child node into improvements with one method per node name
(Backend/Improvements/AddImprovementCollection.cs). Many of those methods only create a single improvement
of a fixed type: from the node's text evaluated against the item's rating, or with no value at all (a flag).
This script finds those and writes them as a Kotlin table, so they need no hand-written code. Everything else
is implemented by hand in BonusHandlers.kt.

Usage: python tools/gen_bonus_table.py <path to chummer5a checkout>
Re-run it when Chummer is updated and commit the result.
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1]) / "Chummer/Backend/Improvements/AddImprovementCollection.cs"
out = Path(__file__).resolve().parent.parent / "core/src/main/kotlin/chummer/core/engine/GeneratedBonusTable.kt"

text = src.read_text(encoding="utf-8-sig")
methods = list(re.finditer(r"public void (\w+)\(XmlNode (\w+)\)\s*\{", text))

NULLCHECK = r"if \(\w+ == null\) throw new ArgumentNullException\(nameof\(\w+\)\); "
UNIQUE = r'(_strUnique|"[^"]*")'
NAME = r'(string\.Empty|"[^"]*"|\w+\.InnerTextViaPool\(\))'
CREATE = (
    r"CreateImprovement\( ?" + NAME
    + r", _objImprovementSource, SourceName, Improvement\.ImprovementType\.(\w+), " + UNIQUE
)
# One improvement whose value is the node text evaluated with the rating.
value_pattern = re.compile(
    NULLCHECK + CREATE + r", ImprovementManager\.ValueTo(Dec|Int)\(_objCharacter, \w+\.InnerTextViaPool\(\), _intRating\) ?\);"
)
# One improvement with no value.
flag_pattern = re.compile(NULLCHECK + CREATE + r" ?\);")
alias_pattern = re.compile(NULLCHECK + r"(\w+)\(\w+\);")


def name_kind(n):
    if n == "string.Empty":
        return "none", ""
    if n.endswith("InnerTextViaPool()"):
        return "text", ""
    return "literal", n.strip('"')


def unique_of(u):
    return "" if u == "_strUnique" else u.strip('"')


simple, alias = {}, {}
for i, m in enumerate(methods):
    end = methods[i + 1].start() if i + 1 < len(methods) else len(text)
    body = text[m.end():end]
    body = body[: body.find("\n        }")]
    body = re.sub(r"\s+", " ", re.sub(r"//[^\n]*", "", body)).strip()
    v = value_pattern.fullmatch(body)
    f = flag_pattern.fullmatch(body)
    a = alias_pattern.fullmatch(body)
    if v:
        kind, lit = name_kind(v.group(1))
        simple[m.group(1)] = (v.group(2), unique_of(v.group(3)), kind, lit, True, v.group(4) == "Int")
    elif f:
        kind, lit = name_kind(f.group(1))
        simple[m.group(1)] = (f.group(2), unique_of(f.group(3)), kind, lit, False, False)
    elif a:
        alias[m.group(1)] = a.group(1)

lines = [
    "package chummer.core.engine",
    "",
    "// GENERATED by tools/gen_bonus_table.py from Chummer's AddImprovementCollection.cs. Do not edit by hand.",
    "",
    "/**",
    " * A bonus node that becomes one improvement of [type]. The improved name is empty, a fixed [literal], or the node text",
    " * ([nameFrom] is none, literal or text). The value is the node text evaluated with the item's rating ([hasValue]),",
    " * rounded when [roundToInt]. [unique] overrides the improvement's unique name; empty means the bonus node's own",
    " * `unique` attribute.",
    " */",
    "data class SimpleBonus(",
    "    val type: String, val unique: String, val nameFrom: String, val literal: String,",
    "    val hasValue: Boolean, val roundToInt: Boolean,",
    ")",
    "",
    "object GeneratedBonusTable {",
    "    val simple: Map<String, SimpleBonus> = mapOf(",
]
for k in sorted(simple):
    t, u, nk, lit, has_value, is_int = simple[k]
    lines.append(
        f'        "{k}" to SimpleBonus("{t}", "{u}", "{nk}", "{lit}", {str(has_value).lower()}, {str(is_int).lower()}),'
    )
lines += ["    )", "", "    /** Nodes that Chummer handles by calling another node's method. */", "    val aliases: Map<String, String> = mapOf("]
for k in sorted(alias):
    lines.append(f'        "{k}" to "{alias[k]}",')
lines += ["    )", "}", ""]
out.write_text("\n".join(lines), encoding="utf-8")
print(f"{len(simple)} simple, {len(alias)} aliases -> {out}")
